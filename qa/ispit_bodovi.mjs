// QA: početna (prag 68/80), uputstvo (80 / 68), rezultat (x/80, bodovi po pitanju).
import { chromium } from "playwright";
const dir = process.argv[2];
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1100, height: 1400 } })).newPage();
const greske = [];
page.on("pageerror", (e) => greske.push(e.message));
page.on("dialog", (d) => d.accept());
await page.goto("http://localhost:3000/", { waitUntil: "networkidle", timeout: 240000 });
const meta = await page.getByText(/40 pitanja/).first().innerText();
console.log("pocetna:", meta);
await page.screenshot({ path: `${dir}/bodovi-1-pocetna.png` });
await page.getByRole("button", { name: /Počni ispit/i }).click();
await page.getByRole("button", { name: /Započni test/i }).waitFor({ timeout: 60000 });
console.log("uputstvo:", (await page.locator("main").innerText()).split("\n").filter((l) => /bod/i.test(l)).join(" | "));
await page.screenshot({ path: `${dir}/bodovi-2-uputstvo.png`, fullPage: true });
await page.getByRole("checkbox").first().check();
await page.getByRole("button", { name: /Započni test/i }).click();
await page.getByRole("button", { name: /Završi ispit/i }).click();
await page.waitForTimeout(800);
const potvrdi = page.getByRole("dialog").getByRole("button", { name: /Završi|Predaj|Da/i });
if (await potvrdi.count()) await potvrdi.first().click();
await page.getByText(/Za prolaz je potrebno/).waitFor({ timeout: 30000 });
const txt = await page.locator("main").innerText();
console.log("rezultat:", txt.match(/\d+\s*\/\s*\d+ bod\w*|Za prolaz[^\n]*/g));
const maks = await page.locator("ol li span.tabular-nums").allInnerTexts();
console.log("bodovi po pitanju:", maks.join(" "), "zbir", maks.reduce((n, s) => n + Number(s.split("/")[1]), 0));
await page.screenshot({ path: `${dir}/bodovi-3-rezultat.png` });
await browser.close();
console.log(JSON.stringify({ greske }));
